/**
 * Solve an SVG captcha string generated by GDT (svg-captcha).
 * Parses path elements, removes noise lines, and maps glyph command sequences to characters.
 *
 * @param svgContent Raw SVG string returned by GDT captcha endpoint
 * @returns Upper-case solved text string (e.g. "8A9AWD")
 */
export function solveGdtSvgCaptcha(svgContent: string): string {
  if (!svgContent || typeof svgContent !== 'string') {
    return '';
  }

  // Extract all <path ...> tags
  const pathMatches = svgContent.matchAll(/<path([^>]+)\/>/gi);
  const characterPaths: { startX: number; char: string }[] = [];

  for (const match of pathMatches) {
    const attrs = match[1];
    const strokeMatch = attrs.match(/stroke="([^"]+)"/i);
    const fillMatch = attrs.match(/fill="([^"]+)"/i);
    const dMatch = attrs.match(/d="([^"]+)"/i);

    if (dMatch) {
      const stroke = strokeMatch ? strokeMatch[1].trim().toLowerCase() : '';
      const fill = fillMatch ? fillMatch[1].trim().toLowerCase() : '';
      const d = dMatch[1];

      // Ignore noise lines: elements with stroke and no fill (or fill="none")
      const isNoise =
        fill === 'none' || (stroke !== '' && stroke !== 'none' && !fill);
      if (isNoise) {
        continue;
      }

      // Extract starting X position (e.g. M25.45 ...)
      const mMatch = d.match(/^M\s*([\d.]+)/i);
      const startX = mMatch ? parseFloat(mMatch[1]) : 0;

      // Extract path command pattern by removing all numbers, dots, and whitespace
      const pattern = d.replace(/[\d.\s]+/g, '');
      const char = GDT_CAPTCHA_MODEL[pattern];

      if (char) {
        characterPaths.push({ startX, char });
      }
    }
  }

  // Sort characters from left to right by starting X position
  characterPaths.sort((a, b) => a.startX - b.startX);

  return characterPaths
    .map((p) => p.char)
    .join('')
    .toUpperCase();
}
